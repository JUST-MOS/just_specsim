"""Conditional, DESI-inspired BGS spectral-information depth for JUST.

The frozen NPZ is generated by build_analysis.py. This is a research model,
not the DESI ETC or an on-sky-calibrated stopping algorithm. Wavelengths are
native JUST pixels; rates are electrons for one 750 s reference exposure.
The input r=19.5 fiducial is a circular exponential (not a de Vaucouleurs)
galaxy. Per-target extinction enters the response once, not the ground sky.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
from scipy.optimize import brentq

HERE = Path(__file__).resolve().parent
ARM_NAMES = "BRZ"
T0 = 750.0


class DepthModel:
    """Compare the wavelength-weighted feature information of fixed scenes.

    The nominal reference uses X=1, zero Galactic reddening, 1.1 arcsec FWHM
    at 6355 A, a hypothetical dark sky with r=21.07, and the frozen JUST model.
    Dark/bright are the previously simulated X=1.2, seeing=0.8 arcsec at
    800 nm scenes. `ebv` changes only source attenuation; transparency changes
    only source transmission. They do not change the given ground-sky model.
    The model uses a fully correlated 1% sky residual, as in the prior mocks.
    """

    def __init__(self, path: Path = HERE / "depth_inputs.npz"):
        with np.load(path, allow_pickle=False) as f:
            self.d = {k: f[k].copy() for k in f.files}
        self.default_ebv = float(self.d["scenario_median_ebv"])

    def information(self, scene: str, time_s: float, *, ebv: float | None = None,
                    transparency: float = 1.0, max_single_s: float = T0,
                    per_arm: bool = False):
        """Return dimensionless proxy Q for one scene and total shutter time.

        Counts and variances reproduce the frozen simulator's sum-coadd model:
        source+sky+stray+dark scale with time; each read adds read variance;
        the 1% sky error is correlated across the complete coadd. A new read
        causes a discontinuity immediately after each max_single_s boundary.
        """
        if scene not in ("nominal", "dark", "bright"):
            raise ValueError("scene must be nominal, dark, or bright")
        if not np.isfinite(time_s) or time_s < 0 or not 0 < max_single_s <= T0:
            raise ValueError("time must be nonnegative and 0 < max_single_s <= 750")
        if not np.isfinite(transparency) or not 0 < transparency <= 1:
            raise ValueError("transparency must be in (0, 1]")
        if ebv is None:
            ebv = 0.0 if scene == "nominal" else self.default_ebv
        if not np.isfinite(ebv) or ebv < 0:
            raise ValueError("E(B-V) must be nonnegative")
        if time_s == 0:
            return np.zeros(3) if per_arm else 0.0
        # Small tolerance keeps exact split boundaries in the lower read count.
        n_read = int(math.ceil(time_s / max_single_s - 1e-12))
        factor = time_s / T0
        q = []
        for arm in ARM_NAMES:
            d = self.d
            response = d[f"{scene}_{arm}_response_no_dust"]
            response = response * transparency * 10**(-.4 * d[f"{arm}_kgal"] * ebv)
            source_750 = response * d[f"{arm}_continuum"]
            sky = d[f"{scene}_{arm}_sky"]
            sky_ref = d[f"{scene}_{arm}_sky_ref"]
            stray = float(d[f"{scene}_{arm}_stray"])
            dark = float(d[f"{arm}_dark"])
            read = float(d[f"{arm}_read"])
            variance = factor * (source_750 + sky + .02*stray + dark)
            variance = variance + n_read*read + (.01*factor*sky_ref)**2
            valid = d[f"{arm}_valid"].astype(bool)
            value = d[f"{arm}_feature_weight"] * (factor*response)**2 / variance
            if np.any(~np.isfinite(value[valid])) or np.any(variance[valid] <= 0):
                raise ValueError("invalid information or variance")
            q.append(float(np.sum(value[valid])))
        return np.asarray(q) if per_arm else float(sum(q))

    def time_for_information(self, scene: str, goal_q: float, *, ebv=None,
                             transparency=1., max_single_s=T0,
                             max_time_s=12000.):
        """First positive solution, searching each read interval separately.

        A summed-coadd read-noise jump creates tiny nonmonotonic intervals, so
        global root finding or a constant survey-speed approximation is unsafe.
        Return NaN if the goal is not reached within the requested range.
        """
        if goal_q < 0 or not np.isfinite(goal_q):
            raise ValueError("information goal must be finite and nonnegative")
        if goal_q == 0:
            return 0.
        if not 0 < max_single_s <= T0 or max_time_s <= 0:
            raise ValueError("invalid exposure split or maximum time")
        n = int(math.ceil(max_time_s / max_single_s))
        for i in range(n):
            lo = i * max_single_s
            hi = min((i+1)*max_single_s, max_time_s)
            # Skip the discontinuity itself; at a boundary the previous
            # interval is always checked first.
            if i:
                lo += max(1e-7, max_single_s*1e-10)
            else:
                lo = 1e-7
            if lo > hi:
                continue
            f = lambda t: self.information(scene, t, ebv=ebv,
                    transparency=transparency, max_single_s=max_single_s) - goal_q
            q_hi = self.information(scene, hi, ebv=ebv, transparency=transparency,
                                    max_single_s=max_single_s)
            # A goal reconstructed through another root finder may differ
            # by roundoff at a read boundary; do not skip a whole interval.
            if np.isclose(q_hi, goal_q, rtol=1e-8, atol=1e-14):
                return float(hi)
            if q_hi > goal_q:
                if f(lo) >= 0:
                    return float(lo)
                return float(brentq(f, lo, hi, xtol=1e-9, rtol=1e-12))
        return float("nan")

    def effective_time(self, scene: str, time_s: float, **kwargs):
        """Find nominal reference seconds with the same Q as this exposure."""
        q = self.information(scene, time_s, **kwargs)
        return self.time_for_information("nominal", q)

    def exposure_for_depth(self, scene: str, nominal_seconds: float, **kwargs):
        """Predict shutter time in a scene for a target nominal depth."""
        q = self.information("nominal", nominal_seconds)
        return self.time_for_information(scene, q, **kwargs)


if __name__ == "__main__":
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("scene", choices=["nominal", "dark", "bright"])
    p.add_argument("--actual-s", type=float, help="convert shutter time to effective seconds")
    p.add_argument("--target-eff-s", type=float, help="predict shutter time for effective seconds")
    p.add_argument("--ebv", type=float, default=None, help="default 0 for nominal, field median otherwise")
    p.add_argument("--transparency", type=float, default=1.)
    p.add_argument("--max-single-s", type=float, default=750.)
    args = p.parse_args()
    if (args.actual_s is None) == (args.target_eff_s is None):
        p.error("specify exactly one of --actual-s and --target-eff-s")
    model = DepthModel()
    opts = dict(ebv=args.ebv, transparency=args.transparency, max_single_s=args.max_single_s)
    if args.actual_s is not None:
        print(f"t_eff_s={model.effective_time(args.scene, args.actual_s, **opts):.6f}")
    else:
        print(f"shutter_s={model.exposure_for_depth(args.scene, args.target_eff_s, **opts):.6f}")
